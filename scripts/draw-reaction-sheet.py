"""Build the beta deck with RDKit. Run with nix-shell --run 'python scripts/draw-reaction-sheet.py'."""
import json
import re
from pathlib import Path

from rdkit import Chem
from rdkit.Chem.Draw import rdMolDraw2D

ROOT = Path(__file__).resolve().parents[1]
LABELS = {0: "R", 2: "R′", 3: "X", 4: "Nu", 5: "Base", 6: "OTs", 7: "OTBS"}


def draw_molecule(smiles):
    params = Chem.SmilesParserParams()
    params.removeHs = False
    molecule = Chem.MolFromSmiles(smiles, params)
    if molecule is None:
        raise ValueError(f"Invalid SMILES: {smiles}")

    for atom in molecule.GetAtoms():
        if atom.GetAtomicNum() == 0:
            atom.SetProp("atomLabel", LABELS[atom.GetIsotope()])
            atom.SetIsotope(0)

    drawer = rdMolDraw2D.MolDraw2DSVG(-1, -1)
    options = drawer.drawOptions()
    options.clearBackground = False
    options.fixedBondLength = 29
    options.padding = 0.1
    options.useBWAtomPalette()
    if " |" in smiles:
        # Keep the source drawing's illustrative wedges, even at a non-stereocenter.
        Chem.ReapplyMolBlockWedging(molecule)
        options.prepareMolsBeforeDrawing = False
    drawer.DrawMolecule(molecule)
    drawer.FinishDrawing()
    svg = drawer.GetDrawingText()
    width, height = map(int, re.search(r"viewBox='0 0 (\d+) (\d+)'", svg).groups())
    markup = svg.split("<!-- END OF HEADER -->", 1)[1].split("</svg>", 1)[0]
    markup = markup.strip().replace("\n", "").replace("#000000", "currentColor")
    return [width, height, markup]


def main():
    deck = json.loads((ROOT / "reaction-sheet.json").read_text())
    if [card["id"] for card in deck] != list(range(1, 44)):
        raise ValueError("Expected one card for each of the 43 non-radical sheet entries.")

    structures = {}
    for card in deck:
        card["image"] = f"cards/{card['id']:02}.png"
        for path in card["paths"]:
            for side in ("substrate", "product"):
                notation = path[side]
                species = [notation] if " |" in notation else notation.split(".")
                for smiles in species:
                    if smiles not in structures:
                        structures[smiles] = draw_molecule(smiles)
                path[side] = species

    def js_array(rows):
        return "[\n" + ",\n".join("  " + json.dumps(row, ensure_ascii=False) for row in rows) + "\n]"

    output = (
        "// Generated by scripts/draw-reaction-sheet.py from reaction-sheet.json.\n"
        f"const sheetDeck = {js_array(deck)};\n"
        f"const sheetStructures = new Map({js_array(structures.items())});\n"
    )
    (ROOT / "reaction-sheet-deck.js").write_text(output)


if __name__ == "__main__":
    main()
